-- 10. Rank the products by their average daily quantity sold	
WITH daily_sales AS (
    SELECT 
        t.product_id, 
        sc.product_name,
        COUNT(DISTINCT t.purchase_date) AS active_days,
        SUM(t.quantity) AS total_quantity
    FROM transactions t
    JOIN sustainable_clothing sc ON t.product_id = sc.product_id
    GROUP BY t.product_id, sc.product_name
)
SELECT 
    product_id, 
    product_name, 
    total_quantity / NULLIF(active_days, 0) AS avg_daily_quantity,
    RANK() OVER (ORDER BY total_quantity / NULLIF(active_days, 0) DESC) AS rank
FROM daily_sales;
